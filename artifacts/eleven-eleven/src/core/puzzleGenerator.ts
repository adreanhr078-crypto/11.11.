// ─── مولد أرقام عشوائي بذري (seeded PRNG) ─────────────────────────────
function createSeededRandom(seed: number) {
  let s = seed;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

